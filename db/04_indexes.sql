CREATE UNIQUE INDEX UQ_PRESTAMOS_ACTIVO_KEY ON PRESTAMOS COMPUTED BY (CASE WHEN ESTADO='ACTIVO' THEN LIBRO_ID ELSE NULL END);
CREATE UNIQUE INDEX UQ_ORDENES_ABIERTA_KEY ON ORDENES_RECLAMO COMPUTED BY (CASE WHEN ESTADO IN ('PENDIENTE','ASIGNADA','EN_RUTA') THEN PRESTAMO_ID ELSE NULL END);
CREATE INDEX IX_PRESTAMOS_ESTADO_VENCE ON PRESTAMOS(ESTADO, FECHA_VENCIMIENTO);
CREATE INDEX IX_PRESTAMOS_LECTOR ON PRESTAMOS(LECTOR_ID, ESTADO);
CREATE INDEX IX_ORDENES_ASIGNADO_ESTADO ON ORDENES_RECLAMO(ASIGNADO_A_USUARIO_ID, ESTADO);
